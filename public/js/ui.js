export function icon(name, cls = '') {
  const s = document.createElementNS(SVG_NS, 'svg');
  s.setAttribute('viewBox', '0 0 24 24');
  s.setAttribute('class', `icon ${cls}`.trim());
  s.setAttribute('aria-hidden', 'true');
  s.innerHTML = ICONS[name] || ''; // static, trusted strings only
  return s;
}

/* ---------- toast / modal ---------- */
let toastHost;
export function toast(message, type = 'info') {
  if (!toastHost) {
    toastHost = h('div', { class: 'toasts', role: 'status', 'aria-live': 'polite' });
    document.body.append(toastHost);
  }
  const t = h('div', { class: `toast ${type}` }, type === 'error' ? icon('alert') : icon('check'), h('span', null, message));
  toastHost.append(t);
  setTimeout(() => t.remove(), type === 'error' ? 6500 : 3500);
}

export function modal({ title, body, actions }) {
  return new Promise((resolve) => {
    const prevFocus = document.activeElement;
    const close = (val) => {
      back.remove();
      document.removeEventListener('keydown', onKey);
      prevFocus?.focus?.();
      resolve(val);
    };
    const onKey = (e) => e.key === 'Escape' && close(null);
    const box = h('div', { class: 'modal', role: 'dialog', 'aria-modal': 'true', 'aria-label': title }, h('h2', null, title), body, h('div', { class: 'modal-actions' }, (actions || []).map((a) => h('button', { type: 'button', class: `btn ${a.class || 'btn-outline'}`, onclick: () => close(a.value) }, a.label))));
    const back = h('div', { class: 'modal-back', onclick: (e) => e.target === back && close(null) }, box);
    document.addEventListener('keydown', onKey);
    document.body.append(back);
    (box.querySelector('input,textarea,select') || box.querySelector('.btn-primary,.btn-brand,.btn-danger') || box).focus?.();
  });
}

export const confirmDialog = (title, message, confirmLabel = 'Confirm', danger = false) =>
  modal({ title, body: h('p', { class: 'muted' }, message), actions: [{ label: 'Cancel', value: false }, { label: confirmLabel, value: true, class: danger ? 'btn-primary' : 'btn-brand' }] }).then(Boolean);

